// Extra sample sheets so some dates have more than one class (BSCS 1A and BSIT 1A both meet on Mondays, etc.).
(function addMoreSheets() {
  const data = window.ATTENDEASE_SAMPLE_DATA;
  const schedule = { 1: ["2026-11-02", "2026-11-05", "2026-11-09", "2026-11-12"], 2: ["2026-11-03", "2026-11-06", "2026-11-10", "2026-11-13"],
                     3: ["2026-11-02", "2026-11-04", "2026-11-09", "2026-11-11"], 4: ["2026-11-03", "2026-11-05", "2026-11-10", "2026-11-12"],
                     5: ["2026-11-04", "2026-11-06", "2026-11-11", "2026-11-13"] };
  Object.keys(schedule).forEach((courseId) => {
    schedule[courseId].forEach((date, i) => {
      if (data.sheets.some((s) => s.courseId === Number(courseId) && s.date === date)) return;
      const records = data.students.filter((s) => s.courseId === Number(courseId)).map((s, n) => {
        const pick = (s.id * 7 + i * 3 + n) % 10;   // simple repeatable pattern instead of random
        let status = pick === 0 ? "absent" : pick === 5 ? "late" : pick === 3 ? "excused" : "present";
        if (s.id === 4) status = "absent";          // one student with many absences, to show the warning
        return { studentId: s.id, status: status };
      });
      data.sheets.push({ id: data.sheets.length + 1, courseId: Number(courseId), date: date, records: records });
    });
  });
})();

